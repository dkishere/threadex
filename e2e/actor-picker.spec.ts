import { expect, test } from "@playwright/test";
import { DEFAULT_MODEL } from "../src/modelCatalog";

test("both actor pickers support rich multiple selection, search, keyboard and selection limits", async ({ page }) => {
  const actors = Array.from({ length: 9 }, (_, index) => ({ id: `actor-${index}`, name: `Actor ${index + 1}`, model: DEFAULT_MODEL,
    effort: "high", rolePrompt: `Specialist perspective ${index + 1}`, isDefault: index < 2 }));
  await page.route("**/api/settings/roundtable-actors", route => route.fulfill({ json: { revision: 1, actors } }));
  await page.route("**/api/sessions/side-test/side-chats", route => route.fulfill({ json: { sideChats: [], jobs: [] } }));
  await page.goto("/e2e/support/actor-picker.html");
  const side = page.getByRole("complementary", { name: "Read-only side chat" });
  await side.getByRole("button", { name: "Select actors", exact: true }).click();
  const sidePicker = side.getByRole("dialog", { name: "Select actors", exact: true });
  await expect(sidePicker.locator(".actor-avatar").first()).toHaveCSS("width", "36px");
  await expect(sidePicker.getByText("Specialist perspective 1", { exact: true })).toBeVisible();
  await sidePicker.getByRole("checkbox", { name: "Actor 1", exact: true }).check();
  await sidePicker.getByRole("checkbox", { name: "Actor 2", exact: true }).check();
  await expect(sidePicker).toBeVisible();
  await sidePicker.getByRole("textbox", { name: "Search actors" }).fill("Actor 9");
  await expect(sidePicker.getByRole("checkbox")).toHaveCount(1);
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Space");
  await expect(sidePicker.getByRole("checkbox")).toBeChecked();
  await page.keyboard.press("Escape");
  await expect(side.getByRole("button", { name: "Select actors", exact: true })).toBeFocused();
  await page.reload();
  await expect(side.getByRole("button", { name: "Select actors", exact: true })).toContainText("3 actors selected");
  await side.getByRole("button", { name: "Select actors", exact: true }).click();
  for (const name of ["Actor 1", "Actor 2", "Actor 9"]) await sidePicker.getByRole("checkbox", { name, exact: true }).uncheck();
  await page.keyboard.press("Escape");
  await expect(side.getByRole("button", { name: "Select actors", exact: true })).toContainText("Default");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Enable round table", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Round table settings", exact: true });
  await settings.getByRole("button", { name: "Select actors", exact: true }).click();
  const picker = settings.getByRole("dialog", { name: "Select actors", exact: true });
  await expect(picker.locator(".actor-avatar").first()).toHaveCSS("width", "36px");
  const bounds = await picker.boundingBox();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "/private/tmp/threadex-actor-multiselect.png" });
  await expect(picker.getByRole("checkbox", { name: "Actor 1", exact: true })).toBeDisabled();
  for (let i = 3; i <= 8; i++) await picker.getByRole("checkbox", { name: `Actor ${i}`, exact: true }).check();
  await expect(picker.getByRole("checkbox", { name: "Actor 9", exact: true })).toBeDisabled();
  await picker.getByRole("checkbox", { name: "Actor 1", exact: true }).uncheck();
  await expect(picker.getByRole("checkbox", { name: "Actor 9", exact: true })).toBeEnabled();
  await page.keyboard.press("Escape");
  await expect(settings).toBeVisible();
  await settings.getByRole("button", { name: "Select actors", exact: true }).click();
  await picker.getByRole("button", { name: "Manage actors", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Agent actor settings", exact: true })).toBeVisible();
});
